function hash(text) {
  let value = 0;
  for (let index = 0; index < text.length; index += 1) value = ((value << 5) - value + text.charCodeAt(index)) | 0;
  return Math.abs(value);
}

function initials(name) {
  return name.split(' ').filter(Boolean).map(part => part[0]).slice(0, 2).join('').toUpperCase();
}

function fallbackPortrait(name, categoryId) {
  const seed = hash(`${categoryId}:${name}`);
  const hueA = seed % 360;
  const hueB = (seed + 48) % 360;
  const label = initials(name);
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 400 400'><defs><linearGradient id='g' x1='0' y1='0' x2='1' y2='1'><stop offset='0%' stop-color='hsl(${hueA} 78% 56%)'/><stop offset='100%' stop-color='hsl(${hueB} 80% 42%)'/></linearGradient></defs><rect width='400' height='400' fill='url(#g)'/><circle cx='200' cy='150' r='68' fill='rgba(255,255,255,.28)'/><rect x='86' y='234' width='228' height='104' rx='52' fill='rgba(255,255,255,.24)'/><text x='200' y='212' text-anchor='middle' font-family='Space Grotesk,DM Sans,sans-serif' font-size='116' font-weight='700' fill='white'>${label}</text></svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

function ensureCompletePortraits(category, portraits) {
  const completed = { ...portraits };
  for (const character of category.characters) {
    if (!completed[character.id]) completed[character.id] = fallbackPortrait(character.name, category.id);
  }
  return completed;
}

async function wikipediaSummaryThumb(title, signal) {
  if (!title) return null;
  const response = await fetch(`https://en.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(title)}`, { signal });
  if (!response.ok) return null;
  const data = await response.json();
  return data?.thumbnail?.source || data?.originalimage?.source || null;
}

function normalizeTitle(value) {
  if (!value) return '';
  return value.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
}

async function wikipediaSearchTitle(query, signal) {
  if (!query) return null;
  const params = new URLSearchParams({ action: 'query', format: 'json', origin: '*', list: 'search', srsearch: query, srlimit: '1' });
  const response = await fetch(`https://en.wikipedia.org/w/api.php?${params}`, { signal });
  if (!response.ok) return null;
  const data = await response.json();
  return data?.query?.search?.[0]?.title || null;
}

async function resolveWikipediaImage(character, signal) {
  const candidates = Array.from(new Set([
    character.wiki,
    character.name,
    normalizeTitle(character.wiki),
    normalizeTitle(character.name),
  ].filter(Boolean)));
  for (const candidate of candidates) {
    const image = await wikipediaSummaryThumb(candidate, signal);
    if (image) return image;
  }
  for (const candidate of candidates) {
    const title = await wikipediaSearchTitle(candidate, signal);
    if (!title) continue;
    const image = await wikipediaSummaryThumb(title, signal);
    if (image) return image;
  }
  return null;
}

async function wikipediaPortraits(category, signal) {
  const params = new URLSearchParams({ action: 'query', format: 'json', origin: '*', prop: 'pageimages', piprop: 'thumbnail|original', pithumbsize: '400', redirects: '1', titles: category.wiki.join('|') });
  const response = await fetch(`https://en.wikipedia.org/w/api.php?${params}`, { signal });
  const portraits = {};
  if (response.ok) {
    const data = await response.json();
    const pages = Object.values(data.query?.pages || {});
    const redirects = data.query?.redirects || [];
    const normalized = data.query?.normalized || [];
    category.characters.forEach(character => {
      let title = normalized.find(item => item.from === character.wiki)?.to || character.wiki;
      title = redirects.find(item => item.from === title)?.to || title;
      const page = pages.find(item => item.title === title);
      portraits[character.id] = page?.thumbnail?.source || page?.original?.source || null;
    });
  }
  const missing = category.characters.filter(character => !portraits[character.id]);
  if (!missing.length) return portraits;
  const recovered = await Promise.all(missing.map(async character => {
    const image = await resolveWikipediaImage(character, signal);
    return [character.id, image];
  }));
  recovered.forEach(([id, image]) => { if (image) portraits[id] = image; });
  return portraits;
}

export async function loadPortraits(category, signal) {
  if (category.characters.every(character => character.image)) return {};
  if (category.id === 'dragon-ball') {
    const response = await fetch('https://dragonball-api.com/api/characters?limit=200', { signal });
    const items = response.ok ? (await response.json()).items : [];
    const aliases = { 'Freezer': 'Frieza', 'Krillin': 'Krilin', 'Cell': 'Celula', 'Beerus': 'Bills', 'Majin Buu': 'Majin Buu', 'Maestro Roshi': 'Master Roshi', 'Androide 18': 'Android 18', 'Androide 17': 'Android 17', 'Chaoz': 'Chiaotzu', 'Tenshinhan': 'Tien Shinhan', 'Goten': 'Son Goten', 'Mr. Satan': 'Mr Satan' };
    const portraits = Object.fromEntries(category.characters.map(character => [character.id, items.find(item => [character.name.toLowerCase(), aliases[character.name]?.toLowerCase()].includes(item.name.toLowerCase()))?.image]));
    const wikiFallback = await wikipediaPortraits(category, signal);
    for (const character of category.characters) {
      if (!portraits[character.id] && wikiFallback[character.id]) portraits[character.id] = wikiFallback[character.id];
    }
    return ensureCompletePortraits(category, portraits);
  }
  const portraits = await wikipediaPortraits(category, signal);
  return ensureCompletePortraits(category, portraits);
}
